export function getStudyPyLessonGuide(chapterHref, lessonTitle) {
  const chapter = studyPyChapters.find((item) => item.href === chapterHref);
  if (!chapter || !chapter.lessons.includes(lessonTitle)) return null;
  const guide = lessonGuides[chapterHref];
  const summary = guide ? guide.summary : "This lesson focuses on " + lessonTitle.toLowerCase() + " within " + chapter.title + ". Use the checkpoints below to turn the topic into a practical skill.";
  const concepts = guide ? guide.concepts : ["Define " + lessonTitle.toLowerCase() + " in your own words.", "Identify the Python syntax or tool used for " + lessonTitle.toLowerCase() + ".", "Explain when you would use " + lessonTitle.toLowerCase() + " and what mistakes to avoid."];
  const example = guide ? guide.example : "# Study focus: " + lessonTitle + "\n# Write a small example, run it, then change one input.\nprint(\"Practice: " + lessonTitle.replaceAll("\\\"", "\\\\\\\"") + "\")";
  return { chapter: chapter.title, category: chapter.category, lesson: lessonTitle, summary, concepts, example, sourceUrl: "https://www.w3schools.com/python/" + chapterHref };
}
